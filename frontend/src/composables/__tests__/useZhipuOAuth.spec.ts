import { effectScope, type EffectScope } from 'vue'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import { zhipuSession, zhipuResult, zhipuCallback } from '@/__tests__/fixtures/zhipuOAuth'
const { init, poll, exchange } = vi.hoisted(() => ({ init: vi.fn(), poll: vi.fn(), exchange: vi.fn() }))
vi.mock('@/api/admin', () => ({ adminAPI: { zhipu: { initOAuth: init, pollOAuth: poll, exchangeCode: exchange } } }))
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key }) }))
import { useZhipuOAuth } from '../useZhipuOAuth'

describe('useZhipuOAuth', () => {
  let scope: EffectScope
  let oauth: ReturnType<typeof useZhipuOAuth>
  beforeEach(() => {
    vi.useFakeTimers()
    init.mockReset().mockImplementation(({ provider }) => Promise.resolve({ ...zhipuSession, provider }))
    poll.mockReset().mockResolvedValue({ status: 'pending' })
    exchange.mockReset().mockResolvedValue(zhipuResult)
    scope = effectScope()
    oauth = scope.run(useZhipuOAuth)!
  })
  afterEach(() => { scope.stop(); vi.useRealTimers() })

  it.each(['bigmodel', 'zai'] as const)('initializes %s, waits for the interval and retains the proxy', async provider => {
    poll.mockResolvedValueOnce({ status: 'pending', interval: 4 }).mockResolvedValueOnce({ status: 'success', result: { ...zhipuResult, provider } })
    await oauth.initOAuth(provider, 8)
    expect(init).toHaveBeenCalledWith({ provider, proxy_id: 8 }, expect.any(AbortSignal))
    await vi.advanceTimersByTimeAsync(1999)
    expect(poll).not.toHaveBeenCalled()
    await vi.advanceTimersByTimeAsync(1)
    expect(poll).toHaveBeenCalledWith({ session_id: 'glm-session', proxy_id: 8 }, expect.any(AbortSignal))
    await vi.advanceTimersByTimeAsync(3999)
    expect(poll).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(1)
    expect(oauth.result.value).toEqual({ ...zhipuResult, provider })
    expect(oauth.loading.value).toBe(false)
    await vi.advanceTimersByTimeAsync(400000)
    expect(poll).toHaveBeenCalledTimes(2)
    expect(oauth.status.value).toBe('success')
  })
  it.each(['expired', 'failed'] as const)('stops for upstream %s and displays its message', async status => {
    poll.mockResolvedValue({ status, message: 'upstream message' })
    await oauth.initOAuth('bigmodel')
    await vi.advanceTimersByTimeAsync(400000)
    expect(oauth.status.value).toBe(status)
    expect(oauth.error.value).toBe('upstream message')
    expect(poll).toHaveBeenCalledOnce()
    expect(oauth.result.value).toBeNull()
  })
  it('expires locally during an in-flight poll and ignores late success', async () => {
    let resolve!: (result: unknown) => void
    poll.mockImplementation(() => new Promise(r => { resolve = r }))
    await oauth.initOAuth('bigmodel')
    await vi.advanceTimersByTimeAsync(300000)
    expect(oauth.status.value).toBe('expired')
    expect(oauth.remainingSeconds.value).toBe(0)
    expect(poll.mock.calls[0][1].aborted).toBe(true)
    resolve({ status: 'success', result: zhipuResult })
    await flushPromises()
    expect(oauth.result.value).toBeNull()
  })
  it('prevents duplicate initialization and overlapping polls', async () => {
    poll.mockImplementation(() => new Promise(() => {}))
    await Promise.all([oauth.initOAuth('bigmodel'), oauth.initOAuth('zai')])
    expect(init).toHaveBeenCalledOnce()
    await vi.advanceTimersByTimeAsync(10000)
    expect(poll).toHaveBeenCalledOnce()
  })
  it('submits the complete callback without parsing it, then stops polling', async () => {
    await oauth.initOAuth('bigmodel', 8)
    expect(await oauth.exchangeCode(` ${zhipuCallback} `)).toBe(true)
    expect(exchange).toHaveBeenCalledWith({ session_id: 'glm-session', callback_url: zhipuCallback, proxy_id: 8 }, expect.any(AbortSignal))
    expect(oauth.result.value).toEqual(zhipuResult)
    await vi.advanceTimersByTimeAsync(400000)
    expect(poll).not.toHaveBeenCalled()
    expect(await oauth.exchangeCode(zhipuCallback)).toBe(false)
    expect(exchange).toHaveBeenCalledOnce()
  })
  it('waits for an active poll before manual exchange and prevents duplicate submissions', async () => {
    let resolvePoll!: (result: unknown) => void
    let resolveExchange!: (result: unknown) => void
    poll.mockImplementationOnce(() => new Promise(r => { resolvePoll = r }))
    exchange.mockImplementationOnce(() => new Promise(r => { resolveExchange = r }))
    await oauth.initOAuth('bigmodel')
    await vi.advanceTimersByTimeAsync(2000)
    const pending = oauth.exchangeCode(zhipuCallback)
    expect(await oauth.exchangeCode(zhipuCallback)).toBe(false)
    expect(exchange).not.toHaveBeenCalled()
    resolvePoll({ status: 'pending' })
    await flushPromises()
    expect(exchange).toHaveBeenCalledOnce()
    await vi.advanceTimersByTimeAsync(10000)
    expect(poll).toHaveBeenCalledOnce()
    resolveExchange(zhipuResult)
    expect(await pending).toBe(true)
    expect(oauth.result.value).toEqual(zhipuResult)
  })
  it('skips manual exchange when the in-flight poll has already completed authorization', async () => {
    let resolve!: (result: unknown) => void
    poll.mockImplementationOnce(() => new Promise(r => { resolve = r }))
    await oauth.initOAuth('bigmodel')
    await vi.advanceTimersByTimeAsync(2000)
    const manual = oauth.exchangeCode(zhipuCallback)
    resolve({ status: 'success', result: zhipuResult })
    await manual
    expect(exchange).not.toHaveBeenCalled()
    expect(oauth.result.value).toEqual(zhipuResult)
  })
  it('resumes polling after a manual exchange error and allows retrying', async () => {
    exchange.mockRejectedValueOnce({ message: 'state mismatch' })
    await oauth.initOAuth('bigmodel')
    expect(await oauth.exchangeCode(zhipuCallback)).toBe(false)
    expect(oauth.error.value).toBe('state mismatch')
    expect(oauth.status.value).toBe('pending')
    await vi.advanceTimersByTimeAsync(2000)
    expect(poll).toHaveBeenCalledOnce()
    expect(await oauth.exchangeCode(zhipuCallback)).toBe(true)
    expect(oauth.error.value).toBe('')
  })
  it('expires locally during manual exchange and ignores a late result', async () => {
    let resolve!: (result: unknown) => void
    exchange.mockImplementationOnce(() => new Promise(r => { resolve = r }))
    await oauth.initOAuth('bigmodel')
    const manual = oauth.exchangeCode(zhipuCallback)
    await flushPromises()
    await vi.advanceTimersByTimeAsync(300000)
    expect(oauth.status.value).toBe('expired')
    expect(exchange.mock.calls[0][1].aborted).toBe(true)
    resolve(zhipuResult)
    expect(await manual).toBe(false)
    expect(oauth.result.value).toBeNull()
  })
  it('ignores late init and manual responses after reset', async () => {
    let resolve!: (result: unknown) => void
    init.mockImplementationOnce(() => new Promise(r => { resolve = r }))
    const old = oauth.initOAuth('bigmodel')
    oauth.resetState()
    await oauth.initOAuth('zai')
    resolve(zhipuSession)
    await old
    expect(oauth.session.value?.provider).toBe('zai')
    exchange.mockImplementationOnce(() => new Promise(r => { resolve = r }))
    const manual = oauth.exchangeCode(zhipuCallback)
    await flushPromises()
    oauth.resetState()
    resolve(zhipuResult)
    expect(await manual).toBe(false)
    expect(oauth.result.value).toBeNull()
    expect(oauth.status.value).toBe('idle')
  })
  it('stops on component unmount', async () => {
    let mountedOAuth!: ReturnType<typeof useZhipuOAuth>
    const wrapper = mount({ setup() { mountedOAuth = useZhipuOAuth(); return () => null } })
    await mountedOAuth.initOAuth('bigmodel')
    await vi.advanceTimersByTimeAsync(2000)
    wrapper.unmount()
    await vi.advanceTimersByTimeAsync(400000)
    expect(poll).toHaveBeenCalledOnce()
    expect(init.mock.calls[0][1].aborted).toBe(true)
  })
  it('handles normal API errors and missing derived credentials', async () => {
    init.mockRejectedValueOnce({ message: 'init failed' })
    expect(await oauth.initOAuth('bigmodel')).toBe(false)
    expect(oauth.error.value).toBe('init failed')
    await oauth.initOAuth('bigmodel')
    poll.mockRejectedValueOnce({ message: 'poll failed' })
    await vi.advanceTimersByTimeAsync(2000)
    expect(oauth.error.value).toBe('poll failed')
    expect(oauth.loading.value).toBe(false)
    await oauth.initOAuth('bigmodel')
    poll.mockResolvedValueOnce({ status: 'success', result: { ...zhipuResult, credentials: {} } })
    await vi.advanceTimersByTimeAsync(2000)
    expect(oauth.status.value).toBe('error')
    expect(oauth.result.value).toBeNull()
  })
})
